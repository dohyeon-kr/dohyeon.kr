import fs from 'node:fs/promises';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import {alignSignupSpans} from './signup-word-alignment.mjs';
import {synthBgm,speechWindows} from './bgm.mjs';
import {resolveSignupModel,validateAlignedScene} from './signup-continuous-model.mjs';
const root=path.resolve(import.meta.dirname,'../..');
const args=process.argv.slice(2),opt=k=>args.find(a=>a.startsWith(`--${k}=`))?.slice(k.length+3);
const inside=(value,base)=>{const p=path.resolve(root,value);if(!p.startsWith(path.join(root,base)+path.sep))throw new Error(`Expected path under ${base}`);return p;};
if(!opt('audio-dir')||!opt('cta-prepared'))throw new Error('Usage: node combine-signup-prepared.mjs --audio-dir=shorts/.tmp/downloaded --cta-prepared=shorts/.tmp/original.json');
const dir=inside(opt('audio-dir'),'shorts/.tmp');
const original=JSON.parse(await fs.readFile(inside(opt('cta-prepared'),'shorts/.tmp'),'utf8'));
const candidate=JSON.parse(await fs.readFile(path.join(root,'shorts/content/signup-phone-number-input/candidate-02.json'),'utf8'));
const body=JSON.parse(await fs.readFile(path.join(dir,'body-prepared.json'),'utf8'));
const receipt=JSON.parse(await fs.readFile(path.join(dir,'receipt.json'),'utf8'));
if(receipt.status!=='completed'||receipt.speechCalls!==1||receipt.transcriptionCalls!==1)throw new Error('Expected the completed single-call audio artifact.');
const transcript=JSON.parse(await fs.readFile(path.join(dir,'transcription.json'),'utf8'));
const aligned=alignSignupSpans(body.beats.map(b=>b.text),transcript.words);
body.beatTimings=aligned.timings;body.captionWords=transcript.words;
validateAlignedScene(body);
if(!original.audioAlreadyMixed)throw new Error('This merge expects the existing mixed CTA release audio.');
const outputDir=path.join(root,'shorts/public/generated/signup-body-once');await fs.mkdir(outputDir,{recursive:true});
const backing=path.join(outputDir,'backing.wav'),mixed=path.join(outputDir,'body.wav');
await fs.writeFile(backing,synthBgm(body.audioDurationSeconds,'pulse-96',speechWindows([body])));
execFileSync('ffmpeg',['-y','-v','error','-i',path.join(dir,'body.wav'),'-i',backing,'-filter_complex','[0:a][1:a]amix=inputs=2:duration=first:normalize=0,alimiter=limit=0.95:level=false:latency=true[out]','-map','[out]','-c:a','pcm_s16le',mixed]);
body.audioPath=path.relative(path.join(root,'shorts/public'),mixed);
const prepared={...candidate,scenes:[body,original.scenes[1]],audioAlreadyMixed:true,audioReuse:{method:'new-continuous-body-with-reused-cta',timingSource:'edit-aligned-whisper-word-timings',transcriptionEditDistance:aligned.editDistance,speechRequestId:receipt.speechRequestId,transcriptionRequestId:receipt.transcriptionRequestId,bodyBgm:'pulse-96',ctaBgm:'existing-release-mix'}};
const model=resolveSignupModel(candidate,prepared);
const output=inside(opt('output')||'shorts/.tmp/signup-phone-number-input-candidate-02.json','shorts/.tmp');
await fs.writeFile(output,JSON.stringify(model.manifest,null,2));
console.log(JSON.stringify({prepared:path.relative(root,output),bodyDuration:body.audioDurationSeconds,videoDuration:model.duration,bodySpeechSplices:0}));
